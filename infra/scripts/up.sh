#!/usr/bin/env bash
# Start a work session: cluster stack up, images pushed, data layer bootstrapped, notes-app + API deployed,
# CloudFront pointed at the new ALB, dashboard published. Prints the URLs at the end.
#
#   infra/scripts/up.sh [--yes] [--skip-images] [--skip-dashboard]
#
# Needs: terraform, aws (signed in), kubectl, jq, envsubst, docker (unless --skip-images), npm (dashboard).
# The foundation stack must have been applied once (infra/README.md). Costs money from here on:
# run infra/scripts/down.sh when the session ends.
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
INFRA="$ROOT/infra"
APPROVE="" SKIP_IMAGES="" SKIP_DASHBOARD=""
for a in "$@"; do
  case "$a" in
    --yes) APPROVE="-auto-approve" ;;
    --skip-images) SKIP_IMAGES=1 ;;
    --skip-dashboard) SKIP_DASHBOARD=1 ;;
    *) echo "unknown option $a" >&2; exit 1 ;;
  esac
done

step() { printf '\n\033[1m==> %s\033[0m\n' "$*"; }
tf_out() { terraform -chdir="$INFRA/$1" output -raw "$2"; }
started=$(date +%s)

step "Reading foundation outputs"
REGION="$(tf_out foundation region)"
ECR_REGISTRY="$(tf_out foundation ecr_registry)"
BUCKET="$(tf_out foundation backup_bucket)"
KMS_ARN="$(tf_out foundation kms_key_arn)"
PUBLIC_URL="$(tf_out foundation public_url)"
# An existing foundation may predate SQS. Bootstrap just the queues in that case,
# before the cluster tries to look up the queue and before the later CloudFront update.
if ! QUEUE_URL="$(tf_out foundation operations_queue_url 2>/dev/null)"; then
  step "Adding the operations queues to the existing foundation"
  terraform -chdir="$INFRA/foundation" apply -input=false $APPROVE \
    -target=aws_sqs_queue.operations_dlq -target=aws_sqs_queue.operations
  QUEUE_URL="$(tf_out foundation operations_queue_url)"
fi
cat > "$INFRA/backend.hcl" <<EOF
bucket       = "$(tf_out foundation tfstate_bucket)"
region       = "$REGION"
encrypt      = true
use_lockfile = true
EOF

step "Cluster stack (VPC, EKS, RDS, ALB controller): ~15-20 minutes on a fresh apply"
terraform -chdir="$INFRA/cluster" init -input=false -backend-config=../backend.hcl >/dev/null
terraform -chdir="$INFRA/cluster" apply -input=false $APPROVE

CLUSTER="$(tf_out cluster cluster_name)"
aws eks update-kubeconfig --region "$REGION" --name "$CLUSTER" >/dev/null
kubectl get nodes

step "Writing jobs/backup-restore/k8s/.env"
TAG="$(git -C "$ROOT" rev-parse --short HEAD)"
ENV_FILE="$ROOT/jobs/backup-restore/k8s/.env"
cat > "$ENV_FILE" <<EOF
# Generated by infra/scripts/up.sh — do not commit.
NAMESPACE=$(tf_out cluster apps_namespace)
AWS_REGION=$REGION
AWS_ACCOUNT_ID=$(tf_out foundation account_id)
ECR_REGISTRY=$ECR_REGISTRY
JOBS_IMAGE=$ECR_REGISTRY/rebound/backup-restore:$TAG
APP_IMAGE_REPO=
S3_BUCKET=$BUCKET
QUEUE_URL=$QUEUE_URL
S3_KMS_KEY_ID=$KMS_ARN
SECRETS_KMS_KEY_ID=$KMS_ARN
DATA_JOBS_ROLE_ARN=$(tf_out cluster data_jobs_role_arn)
RDS_HOST=$(tf_out cluster rds_host)
RDS_MASTER_SECRET_ID=$(tf_out cluster rds_master_secret_arn)
ALB_GROUP=rebound
ALB_URL=$PUBLIC_URL
BACKUP_SCHEDULE="0 2 * * *"
MIN_ROWS=100
API_IMAGE=$ECR_REGISTRY/rebound-api:$TAG
API_ROLE_ARN=$(tf_out cluster api_role_arn)
COGNITO_USER_POOL_ID=$(tf_out foundation cognito_user_pool_id)
COGNITO_CLIENT_ID=$(tf_out foundation cognito_client_id)
DASHBOARD_ORIGIN=$PUBLIC_URL
EOF
set -a; source "$ENV_FILE"; set +a

push() { # <build-context> <registry/repo:tag> [extra docker build args...]
  local ctx="$1" image="$2" repo tag; shift 2
  repo="${image#*/}"; repo="${repo%:*}"; tag="${image##*:}"
  # Tags are immutable in ECR: an image for this commit is never rebuilt.
  if aws ecr describe-images --repository-name "$repo" --image-ids "imageTag=$tag" --region "$REGION" >/dev/null 2>&1; then
    echo "$image already in ECR"; return
  fi
  # Plain manifests (no provenance/SBOM index) so ECR's scan-on-push can scan them, like CI's images.
  docker build --provenance=false --sbom=false "$@" -t "$image" "$ctx"
  docker push "$image"
}

if [ -z "$SKIP_IMAGES" ]; then
  step "Building and pushing images (tag $TAG)"
  aws ecr get-login-password --region "$REGION" | docker login --username AWS --password-stdin "$ECR_REGISTRY"
  push "$ROOT/jobs/backup-restore" "$JOBS_IMAGE"
  push "$ROOT" "$API_IMAGE" -f "$ROOT/api/Dockerfile"
  push "$ROOT/sample-apps/notes-app" "$ECR_REGISTRY/notes-app:$TAG" --build-arg "IMAGE_TAG=$TAG"
fi

step "Data layer: namespace, service account, admin secret, databases"
RD="$ROOT/jobs/backup-restore/k8s/rebound-data.sh"
"$RD" bootstrap
"$RD" provision notes-app
"$RD" provision rebound-platform
"$RD" schedule notes-app

step "Deploying notes-app and the platform API"
APP_REPO="github.com/adamk-codes/cmps297u-paas" APP_ICON=notes \
  APP_DESCRIPTION="Team notes; the sample app for backups and verified restores" \
  "$ROOT/deploy/deploy-app.sh" notes-app "$ECR_REGISTRY/notes-app:$TAG"
envsubst < "$ROOT/api/k8s/api.yaml" | kubectl apply -f -
kubectl rollout status deploy/rebound-api -n "$NAMESPACE" --timeout=180s
kubectl rollout status deploy/rebound-worker -n "$NAMESPACE" --timeout=32m

step "Waiting for the shared ALB"
ALB=""
for _ in $(seq 1 60); do
  ALB="$(kubectl get ingress notes-app -n "$NAMESPACE" -o jsonpath='{.status.loadBalancer.ingress[0].hostname}' 2>/dev/null || true)"
  [ -n "$ALB" ] && break
  sleep 5
done
[ -n "$ALB" ] || { echo "ALB did not come up; check: kubectl describe ingress -n $NAMESPACE" >&2; exit 1; }
echo "ALB: $ALB"

step "Pointing CloudFront at the ALB (HTTPS for /api and /apps): a few minutes"
terraform -chdir="$INFRA/foundation" apply -input=false $APPROVE -var "alb_dns_name=$ALB"

if [ -z "$SKIP_DASHBOARD" ]; then
  step "Publishing the dashboard"
  (
    cd "$ROOT/dashboard"
    npm ci --no-audit --no-fund
    VITE_API_URL="" VITE_AWS_REGION="$REGION" VITE_COGNITO_USER_POOL_ID="$COGNITO_USER_POOL_ID" \
      VITE_COGNITO_CLIENT_ID="$COGNITO_CLIENT_ID" VITE_USE_MOCK=false npm run build
  )
  aws s3 sync "$ROOT/dashboard/dist" "s3://$(tf_out foundation dashboard_bucket)" --delete
  aws cloudfront create-invalidation --distribution-id "$(tf_out foundation cloudfront_distribution_id)" \
    --paths '/*' >/dev/null
fi

step "Session is up in $(( ($(date +%s) - started) / 60 )) min"
cat <<EOF
  Dashboard   $PUBLIC_URL
  API         $PUBLIC_URL/api/healthz
  notes-app   $PUBLIC_URL/apps/notes-app/
  Recovery    $PUBLIC_URL/apps/notes-app-recovery/   (after a restore)

  Backup now:   $RD backup notes-app
  Restore:      $RD restore notes-app latest
  End session:  infra/scripts/down.sh
EOF
